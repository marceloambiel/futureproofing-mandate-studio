test('leaving the website protects unsaved embedded work and rejects unrelated messages', async ({ page }) => {
  test.setTimeout(90000)
  const { host, frame } = await enter(page, 1440)
  await frame.getByRole('button', { name: 'Match candidates to brief', exact: true }).click()
  await expect(frame.getByRole('heading', { name: 'Included profiles', exact: true })).toBeVisible({ timeout: 10000 })
  await frame.getByRole('button', { name: 'Prepare Discussion Brief', exact: true }).click()
  const editor = frame.getByRole('textbox', { name: 'Discussion brief document', exact: true })
  await expect(editor).toBeVisible({ timeout: 10000 })
  await editor.press('ControlOrMeta+End'); await editor.press('Enter'); await editor.pressSequentially('Unsaved host guard question.')
  await host.locator('.demo-guide-header').getByRole('button', { name: 'Return to website' }).click()
  await page.getByRole('link', { name: 'Design process', exact: true }).click()
  const guard = page.getByRole('dialog', { name: 'Unsaved sample changes', exact: true })
  await expect(guard).toBeVisible()
  await guard.getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(host).toBeVisible()
  await expect(editor).toContainText('Unsaved host guard question.')
  await page.evaluate(() => window.postMessage({ channel: 'mandate-workspace-v1', kind: 'return' }, window.location.origin))
  await expect(host).toBeVisible()
  await host.locator('.demo-guide-header').getByRole('button', { name: 'Return to website' }).click()
  await page.getByRole('link', { name: 'Design process', exact: true }).click()
  await expect(guard).toBeVisible()
  await guard.getByRole('button', { name: 'Discard and leave', exact: true }).click()
  await expect(page).toHaveURL(/\/process$/)
})

