import { test, expect, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

async function enter(page: Page, width: number, dashboardEntry = false) {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('/#sample-workspace')
  await page.locator('#sample-workspace').scrollIntoViewIfNeeded()
  const element = page.locator('#sample-workspace iframe')
  const frame = page.frameLocator('#sample-workspace iframe')
  await expect(frame.locator('.bento-task-list')).toBeVisible({ timeout: 15000 })
  await element.evaluate(node => { (node as HTMLIFrameElement).contentDocument!.body.dataset.continuity = 'same-document' })
  const original = await element.elementHandle()
  await expect(frame.getByRole('link', { name: 'Review Northline Integration Search update' })).toBeVisible()
  if (dashboardEntry) await frame.getByRole('link', { name: 'Review Northline Integration Search update' }).click()
  else await page.getByRole('button', { name: "Step into the consultant's seat", exact: true }).click()
  const host = page.locator('.demo-frame-host.is-expanded')
  await expect(host).toHaveAttribute('role', 'dialog')
  await expect(host.locator('.demo-guide-header h2')).toHaveText('Review the changed brief')
  await expect(frame.getByRole('heading', { name: 'Client Brief', exact: true })).toBeVisible()
  const bounds = await host.boundingBox()
  expect(bounds).toMatchObject({ x: 0, y: 0, width, height: 900 })
  expect(await element.evaluate((node, previous) => node === previous, original)).toBe(true)
  await expect(host.locator('.demo-guide-footer').getByRole('button', { name: 'Next', exact: true })).toBeDisabled()
  return { host, frame, element, original }
}

