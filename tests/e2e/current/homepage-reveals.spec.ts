import {test,expect} from '@playwright/test'
for(const width of [1440,390])test(`sections reveal once without hiding keyboard targets at ${width}`,async({page})=>{
 await page.setViewportSize({width,height:900})
 await page.goto('/')
 const title=page.locator('#homepage-faq-title')
 await expect(title).toHaveAttribute('data-home-reveal','true')
 await expect(title).toHaveCSS('opacity','0')
 await title.scrollIntoViewIfNeeded()
 await expect(title).toHaveAttribute('data-home-visible','true')
 await expect(title).toHaveCSS('opacity','1')
 await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}))
 await expect(title).toHaveCSS('opacity','1')
 const contact=page.locator('.homepage-faq-contact button')
 await contact.focus()
 await expect(contact).toBeFocused()
 await expect(page.locator('.homepage-faq-contact')).toHaveCSS('opacity','1')
 await contact.click()
 await expect(page.getByRole('dialog',{name:'Request a conversation',exact:true})).toBeVisible()
})
test('reduced motion leaves every group immediately visible',async({page})=>{
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/')
 await expect(page.locator('#homepage-faq-title')).toHaveCSS('opacity','1')
 await expect(page.locator('[data-home-reveal]')).toHaveCount(0)
})
