import {test,expect} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
for(const width of [1440,390,320])test(`website video hero is readable and usable at ${width}`,async({page})=>{
 await page.setViewportSize({width,height:900})
 await page.goto('/')
 const header=page.locator('.marketing-v2>.site-header')
 await expect(header.getByRole('img',{name:'Mandate',exact:true})).toHaveAttribute('src','/brand/mandate.svg')
 const hero=page.locator('.mandate-hero')
 const videos=hero.locator('video')
 await expect(videos).toHaveCount(2)
 await expect(hero.getByRole('heading',{level:1})).toHaveText('The business has changed. What should its next leader bring?')
 await expect(hero.locator('.eyebrow')).toHaveText('Executive search for consequential leadership')
 await expect(hero.getByRole('link',{name:'Explore sample workspace'})).toHaveAttribute('href','#sample-workspace')
 await expect(hero.getByRole('button',{name:'Request a conversation',exact:true})).toBeVisible()
 await expect.poll(()=>videos.nth(0).evaluate(video=>(video as HTMLVideoElement).currentTime)).toBeGreaterThan(0)
 expect(await videos.evaluateAll(nodes=>nodes.every(node=>(node as HTMLVideoElement).muted))).toBe(true)
 await videos.nth(0).evaluate(video=>{const clip=video as HTMLVideoElement;clip.currentTime=clip.duration-.15})
 await expect(videos.nth(1)).toHaveClass('is-active')
 await expect.poll(()=>videos.nth(1).evaluate(video=>(video as HTMLVideoElement).readyState)).toBeGreaterThanOrEqual(2)
 await videos.nth(1).evaluate(video=>{const clip=video as HTMLVideoElement;clip.currentTime=clip.duration-.15})
 await expect(videos.nth(0)).toHaveClass('is-active')
 await hero.getByRole('button',{name:'Pause background videos'}).click()
 expect(await videos.evaluateAll(nodes=>nodes.every(video=>(video as HTMLVideoElement).paused))).toBe(true)
 const heading=await hero.getByRole('heading',{level:1}).boundingBox()
 expect(Math.abs(heading!.x+heading!.width/2-width/2)).toBeLessThan(2)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:`docs/qa/2026-11-13/home-01/hero-${width}.png`})
 const results=await new AxeBuilder({page}).include('.site-header').include('.mandate-hero').withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()
 expect(results.violations).toEqual([])
 if(width<801){
  const menu=header.locator('summary')
  await menu.click()
  await expect(header.getByRole('navigation',{name:'Mobile main navigation'})).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).toBeFocused()
  await expect(header.locator('details')).not.toHaveAttribute('open')
 }
 await hero.getByRole('button',{name:'Request a conversation',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'Request a conversation',exact:true})).toBeVisible()
})
test('website videos stay static for reduced motion until explicitly played',async({page})=>{
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/')
 const hero=page.locator('.mandate-hero')
 await expect(hero.getByRole('button',{name:'Play background videos'})).toBeVisible()
 expect(await hero.locator('video').evaluateAll(nodes=>nodes.every(video=>(video as HTMLVideoElement).paused))).toBe(true)
 await hero.getByRole('button',{name:'Play background videos'}).click()
 await expect.poll(()=>hero.locator('video').first().evaluate(video=>(video as HTMLVideoElement).currentTime)).toBeGreaterThan(0)
})

test('homepage navigation targets the existing sections and sample without replacing the embed',async({page})=>{
 await page.goto('/')
 const frame=page.locator('#sample-workspace iframe')
 await expect(frame).toHaveAttribute('src','/workspace?preview=1')
 const originalFrame=await frame.elementHandle()
 for(const [name,id] of [['Our approach','our-process'],['Leadership challenges','challenges'],['Sample workspace','sample-workspace']]){
  await page.locator('.site-header').getByRole('link',{name,exact:true}).click()
  await expect(page).toHaveURL(new RegExp(`#${id}$`))
  await expect(page.locator(`#${id}`)).toBeInViewport()
  await page.evaluate(()=>window.scrollTo(0,0))
 }
 await page.locator('.mandate-hero').getByRole('link',{name:'Explore sample workspace'}).click()
 await expect(page.locator('#sample-workspace')).toBeInViewport()
 await expect(frame).toHaveCount(1)
 expect(await frame.evaluate((node,original)=>node===original,originalFrame)).toBe(true)
 await page.setViewportSize({width:390,height:900})
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.locator('summary[aria-label="Toggle navigation"]').click()
 await page.getByRole('navigation',{name:'Mobile main navigation'}).getByRole('link',{name:'Sample workspace',exact:true}).click()
 await expect(page.locator('.marketing-mobile-navigation')).not.toHaveAttribute('open')
 await expect(page.locator('#sample-workspace')).toBeInViewport()
})
