import {chromium} from '@playwright/test'
import {mkdir,writeFile,copyFile} from 'node:fs/promises'
const out='docs/run/mandate-studio-v1/evidence/screenshots'
await mkdir(out,{recursive:true})
const browser=await chromium.launch({headless:true})
const context=await browser.newContext({viewport:{width:1440,height:1000}})
const page=await context.newPage()
const errors=[];page.on('pageerror',e=>errors.push(e.message))
const origin=process.env.CAPTURE_BASE_URL||'http://127.0.0.1:5173'
async function snap(name,route,fullPage=true){if(route)await page.goto(origin+route);await page.evaluate(()=>document.fonts.ready);await page.screenshot({path:`${out}/${name}.png`,fullPage,animations:'disabled'});console.log(name)}
await snap('homepage-desktop','/')
await snap('assignment-desktop','/workspace/assignment')
await snap('comparison-desktop','/workspace/candidates')
await page.getByRole('button',{name:'View evidence for Candidate A',exact:true}).click()
await snap('evidence-desktop',null,false)
await page.keyboard.press('Escape')
await snap('discussion-desktop','/workspace/discussion')
await page.getByRole('button',{name:'Edit discussion brief',exact:true}).click()
await snap('editor-desktop',null,false)
await page.getByRole('button',{name:'Cancel',exact:true}).click()
await page.getByRole('button',{name:'Compare versions',exact:true}).click()
await snap('versions-desktop',null,false)
await page.getByRole('button',{name:'Restore this mandate section as draft',exact:true}).click()
await snap('restore-confirmation-desktop',null,false)
await page.getByRole('button',{name:'Restore as draft',exact:true}).click()
await snap('restored-conflict-desktop',null)
await page.getByRole('button',{name:'Update to revised mandate',exact:true}).click()
await page.getByRole('button',{name:'Save changes',exact:true}).click()
await page.getByRole('button',{name:'Mark ready for review',exact:true}).click()
await snap('ready-desktop',null)
await snap('unknown-route','/unknown-page',false)
await page.setViewportSize({width:390,height:844})
await snap('homepage-mobile','/')
await snap('assignment-mobile','/workspace/assignment')
await snap('comparison-mobile','/workspace/candidates')
await page.getByRole('button',{name:'View evidence for Candidate C',exact:true}).click()
await snap('evidence-mobile',null,false)
await page.keyboard.press('Escape')
await snap('discussion-mobile','/workspace/discussion')
await page.getByRole('button',{name:'Compare versions',exact:true}).click()
await snap('versions-mobile',null,false)
await page.keyboard.press('Escape')
for(const name of ['comparison-desktop','discussion-desktop','comparison-mobile'])await copyFile(`${out}/${name}.png`,`public/process/${name}.png`)
await writeFile(`${out}/console-errors.json`,JSON.stringify(errors,null,2))
await browser.close()
